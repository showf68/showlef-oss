  var lang = 'en';

  function detect() {
    var l = 'en';
    try { l = (chrome.i18n && chrome.i18n.getUILanguage ? chrome.i18n.getUILanguage() : navigator.language) || 'en'; } catch (e) { }
    l = l.slice(0, 2).toLowerCase();
    if (l === 'iw') l = 'he';
    return D[l] ? l : 'en';
  }

  function init() {
    return chrome.storage.local.get('settings').then(function (r) {
      var s = r.settings || {};
      lang = D[s.lang] ? s.lang : detect();
      return lang;
    }, function () { lang = detect(); return lang; });
  }

  function t(k, v) {
    var s = (D[lang] && D[lang][k]) || D.en[k] || k;
    if (v) for (var n in v) s = s.split('{' + n + '}').join(v[n]);
    return s;
  }

  function fmtSize(b) {
    if (!b || b <= 0) return '';
    var u = [t('uKB'), t('uMB'), t('uGB')];
    var x = b / 1024, i = 0;
    while (x >= 1024 && i < 2) { x /= 1024; i++; }
    return (x < 10 ? x.toFixed(1) : Math.round(x)) + ' ' + u[i];
  }

  function fmtDur(sec) {
    if (!sec || sec < 0 || !isFinite(sec)) return '';
    sec = Math.round(sec);
    var h = Math.floor(sec / 3600), m = Math.floor(sec % 3600 / 60), s = sec % 60;
    var p = function (n) { return n < 10 ? '0' + n : '' + n; };
    return h ? h + ':' + p(m) + ':' + p(s) : m + ':' + p(s);
  }

  // Temps restant court : « 13 s » sous la minute, sinon m:ss (h:mm:ss).
  function fmtLeft(sec) {
    if (!sec || sec < 0 || !isFinite(sec)) return '';
    sec = Math.round(sec);
    return sec < 60 ? t('secs', { n: sec }) : fmtDur(sec);
  }

  // Message d'erreur lisible (bouton de la page, popup) ; en hebreu, jamais de texte technique en lettres latines.
  // `code` : code court envoye par le programme (champ `code` de list) ; une phrase + le geste, dans NOTRE langue.
  var CODES = { denied: 'errDenied', gone: 'errGone', busy: 'errServer', net: 'errNet', disk: 'errDisk', drm: 'errDrm',
    noFormat: 'errNoFormat', blocked: 'errBlocked', capStopped: 'errCapStopped', generic: 'errGeneric' };
  function humanErr(e, code) {
    if (code && CODES[code] && code !== 'generic') return t(CODES[code]);
    e = String(e || '');
    if (e === 'needApp' || e === 'needUpdate' || e === 'blocked' || e === 'duplicate') return t(e);
    if (/HTTP 40[13]/.test(e)) return t('errDenied');
    if (/HTTP 4(04|10)/.test(e)) return t('errGone');
    if (/HTTP (429|5\d\d)/.test(e)) return t('errServer');
    if (/not enough space|disk full|No space left|espace insuffisant/i.test(e)) return t('errDisk');
    if (/incomplete|timed? ?out|connect|remote name|reset|aborted/i.test(e)) return t('errNet');
    if (!e || e === '?') return t('errGeneric');
    if (lang === 'he' && /[A-Za-z]/.test(e)) return t('errGeneric');
    return e;
  }

